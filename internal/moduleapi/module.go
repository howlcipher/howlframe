// Package moduleapi contains shared source-level helpers for generated module
// targets. It has no dependency on a compiler backend.
package moduleapi

import (
	"fmt"
	"strings"

	"github.com/howlcipher/howlframe/internal/ast"
)

// Exports returns the top-level defuns wrapped by (export ...). Exports in
// used modules remain private to their containing module.
func Exports(root *ast.Node) []*ast.Node {
	var out []*ast.Node
	if root == nil || root.Type != "List" {
		return nil
	}
	for _, n := range root.Children[1:] {
		if n.Type != "List" || len(n.Children) != 2 || n.Children[0].Value != "export" {
			continue
		}
		d := n.Children[1]
		if d.Type == "List" && len(d.Children) >= 4 && d.Children[0].Value == "defun" {
			out = append(out, d)
		}
	}
	return out
}

// PublicName applies the module backend's stable mapping for namespaced
// source functions used as ESM export names.
func PublicName(name string) string {
	if !strings.Contains(name, "/") {
		return name
	}
	parts := strings.Split(name, "/")
	public := parts[0]
	for _, part := range parts[1:] {
		if part != "" {
			public += "_" + part
		}
	}
	return public
}

// DeclarationsTS returns Promise-based TypeScript declarations inferred from
// the exported functions' type hints.
func DeclarationsTS(exports []*ast.Node, sig func(*ast.Node) ([]ast.TypeInfo, ast.TypeInfo)) string {
	var b strings.Builder
	b.WriteString("// Generated by the HowlFrame compiler from the program's type hints.\n")
	for _, d := range exports {
		params, ret := sig(d)
		names := ast.ParamNames(d.Children[2])
		parts := make([]string, len(names))
		for i, n := range names {
			t := ast.Layout(ast.Unknown)
			if i < len(params) {
				t = params[i]
			}
			parts[i] = fmt.Sprintf("%s: %s", n, tsType(t))
		}
		name := PublicName(d.Children[1].Value)
		fmt.Fprintf(&b, "export declare function %s(%s): Promise<%s>;\n", name, strings.Join(parts, ", "), tsType(ret))
	}
	return b.String()
}

func tsType(t ast.TypeInfo) string {
	switch t.Kind {
	case ast.String:
		return "string"
	case ast.Int, ast.Float:
		return "number"
	case ast.Bool:
		return "boolean"
	case ast.Void:
		return "void"
	case ast.List:
		if t.Element != nil && t.Element.Kind != ast.Unknown && t.Element.Kind != ast.Any {
			return tsType(*t.Element) + "[]"
		}
		return "unknown[]"
	case ast.Dict:
		return "Record<string, unknown>"
	}
	switch t.Name {
	case "dict":
		return "Record<string, unknown>"
	case "list":
		return "unknown[]"
	}
	return "unknown"
}
