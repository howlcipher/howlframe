package textcase

import (
	"fmt"
	"os"
	"strings"
	"testing"
	"unicode"
)

// tableSource is table.go as generated from the toolchain's
// unicode.CaseRanges, which must be Unicode UnicodeVersion.
func tableSource() string {
	var b strings.Builder
	b.WriteString(`// Code generated by TestTableIsCurrent from Go's unicode.CaseRanges (Unicode ` + unicode.Version + `); DO NOT EDIT.
// Regenerate with a toolchain of that Unicode version:
// HOWLFRAME_UPDATE=1 go test ./internal/textcase -run TestTableIsCurrent

package textcase

import "unicode"

// CaseRanges is unicode.CaseRanges of Unicode UnicodeVersion.
var CaseRanges = []unicode.CaseRange{
`)
	for _, cr := range unicode.CaseRanges {
		fmt.Fprintf(&b, "\t{Lo: 0x%04X, Hi: 0x%04X, Delta: [unicode.MaxCase]rune{%d, %d, %d}},\n", cr.Lo, cr.Hi, cr.Delta[0], cr.Delta[1], cr.Delta[2])
	}
	b.WriteString("}\n")
	return b.String()
}

// TestTableIsCurrent checks table.go against the toolchain's tables when
// they are the pinned Unicode version (Go 1.25 and 1.26; CI's build job).
// Other toolchains cannot regenerate it, and the pinned table is what
// makes the result the same on them.
func TestTableIsCurrent(t *testing.T) {
	if unicode.Version != UnicodeVersion {
		t.Skipf("the toolchain has Unicode %s; table.go is Unicode %s and is checked on a toolchain of that version", unicode.Version, UnicodeVersion)
	}
	want := tableSource()
	if os.Getenv("HOWLFRAME_UPDATE") == "1" {
		if err := os.WriteFile("table.go", []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("table.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatal("table.go is out of date: HOWLFRAME_UPDATE=1 go test ./internal/textcase -run TestTableIsCurrent")
	}
}

// On a toolchain of the pinned version, every code point and string maps
// as Go's own functions map it.
func TestSameAsGoOnPinnedVersion(t *testing.T) {
	if unicode.Version != UnicodeVersion {
		t.Skipf("the toolchain has Unicode %s, not %s", unicode.Version, UnicodeVersion)
	}
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		if got, want := LowerRune(r), unicode.ToLower(r); got != want {
			t.Fatalf("LowerRune(%U) = %U, unicode.ToLower %U", r, got, want)
		}
		if got, want := UpperRune(r), unicode.ToUpper(r); got != want {
			t.Fatalf("UpperRune(%U) = %U, unicode.ToUpper %U", r, got, want)
		}
	}
	for _, s := range []string{"", "Hello, World", "ÀÉÎõü", "İstanbul ς Σ", "ǅ ǈ ǋ", "ɤ ꟛ Ɤ", "a\xffb\xc3", "\xed\xa0\x80"} {
		if got, want := ToLower(s), strings.ToLower(s); got != want {
			t.Errorf("ToLower(%q) = %q, strings.ToLower %q", s, got, want)
		}
		if got, want := ToUpper(s), strings.ToUpper(s); got != want {
			t.Errorf("ToUpper(%q) = %q, strings.ToUpper %q", s, got, want)
		}
	}
}

// Whatever the toolchain, the code points Unicode 17 added mappings for
// keep their Unicode 15 case (bugs.md #69).
func TestPinnedWhateverTheToolchain(t *testing.T) {
	for _, c := range []struct{ in, lower, upper string }{
		{"ɤ", "ɤ", "ɤ"},                      // U+0264: Unicode 17 uppercases it to U+A7CB
		{"ꟛ Ɤ", "ꟛ Ɤ", "ꟛ Ɤ"},                // U+A7DB, U+A7CB: cased in Unicode 17
		{"ƛ", "ƛ", "ƛ"},                      // U+019B: Unicode 17 uppercases it to U+A7DC
		{"Straße ǅ", "straße ǆ", "STRAßE Ǆ"}, // ß has no single upper-case rune
	} {
		if got := ToLower(c.in); got != c.lower {
			t.Errorf("ToLower(%q) = %q, want %q", c.in, got, c.lower)
		}
		if got := ToUpper(c.in); got != c.upper {
			t.Errorf("ToUpper(%q) = %q, want %q", c.in, got, c.upper)
		}
	}
}
