package javascript

import (
	"fmt"
	"sort"
	"strings"

	"github.com/howlcipher/howlframe/internal/ast"
)

// ModuleExports returns the defuns a web_app exports at its top level, as
// (export (defun name ...)). Exports inside used modules are module-private
// API and are not included.
func ModuleExports(root *ast.Node) []*ast.Node {
	var out []*ast.Node
	if root == nil || root.Type != "List" {
		return nil
	}
	for _, n := range root.Children[1:] {
		if n.Type == "List" && len(n.Children) == 2 && n.Children[0].Value == "export" {
			d := n.Children[1]
			if d.Type == "List" && len(d.Children) >= 4 && d.Children[0].Value == "defun" {
				out = append(out, d)
			}
		}
	}
	return out
}

// GenerateJSModule generates the program as an ES module that exports the
// given functions by name. The node:test file is the same as GenerateJSCode's.
// Host operations that reach Node through require (env, exec, read_file,
// write_file, mkdir) are refused: a module has no require.
func GenerateJSModule(root *ast.Node, exports []*ast.Node) (string, string, error) {
	if len(exports) == 0 {
		return "", "", fmt.Errorf("--module: the program has no top-level (export (defun ...)) to export")
	}
	code, testCode := GenerateJSCode(root)
	var refused []string
	for name, used := range map[string]bool{"env": jsNeedsEnv, "exec": jsNeedsExec, "read_file": jsNeedsReadFile, "write_file": jsNeedsWriteFile, "mkdir": jsNeedsMkdir} {
		if used {
			refused = append(refused, name)
		}
	}
	if len(refused) > 0 {
		sort.Strings(refused)
		return "", "", fmt.Errorf("--module: %s not available in --module output (it needs Node's require)", strings.Join(refused, ", "))
	}
	names := make([]string, 0, len(exports))
	for _, d := range exports {
		names = append(names, sanitizeJSName(d.Children[1].Value))
	}
	return code + fmt.Sprintf("export { %s };\n", strings.Join(names, ", ")), testCode, nil
}

// DeclarationsTS returns TypeScript declarations for the exported functions.
// sig reports each function's parameter and return types, as the checker
// resolved them. Every generated function is async, so each returns a Promise.
func DeclarationsTS(exports []*ast.Node, sig func(*ast.Node) ([]ast.TypeInfo, ast.TypeInfo)) string {
	var b strings.Builder
	b.WriteString("// Generated by the HowlFrame compiler from the program's type hints.\n")
	for _, d := range exports {
		params, ret := sig(d)
		names := ast.ParamNames(d.Children[2])
		parts := make([]string, len(names))
		for i, n := range names {
			t := ast.Layout(ast.Unknown)
			if i < len(params) {
				t = params[i]
			}
			parts[i] = fmt.Sprintf("%s: %s", n, tsType(t))
		}
		fmt.Fprintf(&b, "export declare function %s(%s): Promise<%s>;\n", sanitizeJSName(d.Children[1].Value), strings.Join(parts, ", "), tsType(ret))
	}
	return b.String()
}

func tsType(t ast.TypeInfo) string {
	switch t.Kind {
	case ast.String:
		return "string"
	case ast.Int, ast.Float:
		return "number"
	case ast.Bool:
		return "boolean"
	case ast.Void:
		return "void"
	case ast.List:
		if t.Element != nil && t.Element.Kind != ast.Unknown && t.Element.Kind != ast.Any {
			return tsType(*t.Element) + "[]"
		}
		return "unknown[]"
	case ast.Dict:
		return "Record<string, unknown>"
	}
	// The checker leaves the "dict" and "list" hints unresolved (Unknown,
	// named) so their values stay unchecked; the declaration still names the
	// container.
	switch t.Name {
	case "dict":
		return "Record<string, unknown>"
	case "list":
		return "unknown[]"
	}
	return "unknown"
}
