// Loader returns the Node.js module that runs a compiled cli_app:
// node app.mjs [args]. It is the same for every program. It provides the
// host imports (print, stderr and exit) and reports an uncaught error
// like the VM: a JSON line on standard error and exit status 1.
func Loader() string { return loader("app.wasm", "app.wasm (a cli_app)") }

// TestLoader returns the Node.js module that runs a test module
// (CompileTests): node app.test.mjs. The tests report themselves; the
// loader is Loader's for app.test.wasm.
func TestLoader() string { return loader("app.test.wasm", "app.test.wasm (a program's tests)") }

const nodeModuleOutputRuntime = `function howlFrameStderr(v) {
  const s = v === null || v === undefined ? "" : String(v);
  if (typeof process !== "undefined" && process.stderr && typeof process.stderr.write === "function") process.stderr.write(s);
  else if (typeof console !== "undefined") console.error(s);
}
function howlFrameExit(code, where) {
  if (typeof process !== "undefined" && typeof process.exit === "function") process.exit(code);
  const e = new Error("EXIT " + code + " at " + where);
  e.howlFrameExit = true;
  throw e;
}
`

// ModuleLoader returns a Node ESM adapter for a WasmGC module's exported
// HowlFrame functions. Calls are serialized because the current resumable
// runtime has one active fiber stack per instance.
func ModuleLoader(exports []string, voids map[string]bool) string {
	var b strings.Builder
	b.WriteString(`// Generated by the HowlFrame compiler. Exposes a WasmGC SDK as Node ESM.
import { readFileSync } from "node:fs";
`)
	b.WriteString(nodeModuleOutputRuntime)
	b.WriteString(browserLoaderCore)
	b.WriteString(`
const wasm = readFileSync(new URL("./app.wasm", import.meta.url));
const { instance } = await WebAssembly.instantiate(wasm, imports);
ex = instance.exports;
await task(() => { ex.main(); });
let moduleQueue = Promise.resolve();
function invoke(name, args, returnsVoid) {
  const call = moduleQueue.then(async () => {
    let result;
    await task(() => { result = ex[name](...args.map(toWasm)); });
    return returnsVoid ? undefined : toJS(result);
  });
  moduleQueue = call.then(() => undefined, () => undefined);
  return call;
}
`)
	for _, name := range exports {
		fmt.Fprintf(&b, "export function %s(...args) { return invoke(%q, args, %t); }\n", moduleapi.PublicName(name), name, voids[name])
	}
	return b.String()
}

func loader(file, what string) string {
	return `// Generated by the HowlFrame compiler. Runs ` + what + ` in Node.js.
import { readFileSync } from "node:fs";

const wasm = readFileSync(new URL("./` + file + `", import.meta.url));
let ex;
const decoder = new TextDecoder();
// A string's bytes as they are: output is written byte for byte, like the
// VM's, even where they are not valid UTF-8.
const bytesOf = (s) => {
  const n = ex.__hf_str_len(s);
  const bytes = new Uint8Array(n);
  for (let i = 0; i < n; i++) bytes[i] = ex.__hf_str_byte(s, i);
  return bytes;
};
const text = (s) => decoder.decode(bytesOf(s));
const newline = new Uint8Array([10]);
const imports = {
  hf: {
    print: (s) => { process.stdout.write(bytesOf(s)); process.stdout.write(newline); },
    stderr: (s) => { process.stderr.write(bytesOf(s)); },
    exit: (code) => { process.exit(code); },
  },
};
const { instance } = await WebAssembly.instantiate(wasm, imports);
ex = instance.exports;
ex.main();
const err = ex.__hf_error();
if (err !== null) {
  // The error is "CODE: message", with the VM's error code.
  const t = text(err);
  const at = t.indexOf(": ");
  const [code, message] = at < 0 ? ["RUNTIME_ERROR", t] : [t.slice(0, at), t.slice(at + 2)];
  process.stderr.write(JSON.stringify({ phase: "runtime", code, function: "main", message }) + "\n");
  process.exit(1);
}
`
}
