package wasmgc

// Loader returns the Node.js module that runs a compiled cli_app:
// node app.mjs [args]. It is the same for every program. It provides the
// host imports (print, and the shortest digits of a float until the
// standard library formats floats itself) and reports an uncaught error
// like the VM: a JSON line on standard error and exit status 1.
func Loader() string {
	return `// Generated by the HowlFrame compiler. Runs app.wasm (a cli_app) in Node.js.
import { readFileSync } from "node:fs";

const wasm = readFileSync(new URL("./app.wasm", import.meta.url));
let ex;
const decoder = new TextDecoder();
const text = (s) => {
  const n = ex.__hf_str_len(s);
  const bytes = new Uint8Array(n);
  for (let i = 0; i < n; i++) bytes[i] = ex.__hf_str_byte(s, i);
  return decoder.decode(bytes);
};
// The shortest round-trip digits of a positive finite float, and where its
// decimal point falls (value = 0.DIGITS x 10^point).
const parts = (x) => {
  const [mantissa, exponent] = x.toExponential().split("e");
  return { digits: BigInt(mantissa.replace(".", "")), point: Number(exponent) + 1 };
};
// Go's ParseFloat syntax: decimal with optional exponent, inf, infinity
// and nan in any case; anything else is not a number.
const goFloat = (t) => {
  if (/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(t)) return Number(t);
  if (/^[+-]?(inf|infinity)$/i.test(t)) return t.startsWith("-") ? -Infinity : Infinity;
  return NaN;
};
const imports = {
  hf: {
    print: (s) => { process.stdout.write(text(s) + "\n"); },
    float_digits: (x) => parts(x).digits,
    float_point: (x) => parts(x).point,
    parse_float: (s) => goFloat(text(s)),
    parse_float_ok: (s) => (Number.isNaN(goFloat(text(s))) && !/^[+-]?nan$/i.test(text(s)) ? 0 : 1),
  },
};
const { instance } = await WebAssembly.instantiate(wasm, imports);
ex = instance.exports;
ex.main();
const err = ex.__hf_error();
if (err !== null) {
  process.stderr.write(JSON.stringify({ phase: "runtime", code: "RUNTIME_ERROR", function: "main", message: text(err) }) + "\n");
  process.exit(1);
}
`
}
